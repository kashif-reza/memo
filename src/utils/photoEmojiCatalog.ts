export interface ParsedCropRect {
  x: number;
  y: number;
  w: number;
  h: number;
  sw: number;
  sh: number;
}

/**
 * Parses a photo URL that may contain a `#crop=x,y,w,h,sw,sh` fragment pointing to a
 * solo reaction sticker inside one of the official multi-reaction sheet images.
 */
export function parseCropUrl(url: string | null | undefined): {
  baseUrl: string;
  crop: ParsedCropRect | null;
} {
  if (!url) return { baseUrl: '', crop: null };
  const hashIdx = url.indexOf('#crop=');
  if (hashIdx === -1) {
    return { baseUrl: url, crop: null };
  }
  const baseUrl = url.slice(0, hashIdx);
  const raw = url.slice(hashIdx + 6);
  const parts = raw.split(',').map(Number);
  if (parts.length === 6 && parts.every((n) => Number.isFinite(n) && n >= 0)) {
    const [x, y, w, h, sw, sh] = parts;
    if (w > 0 && h > 0 && sw > 0 && sh > 0) {
      return { baseUrl, crop: { x, y, w, h, sw, sh } };
    }
  }
  return { baseUrl, crop: null };
}

/**
 * Computes exact SVG `<image>` attributes so that either a full solo photo OR a `#crop=x,y,w,h,sw,sh`
 * region from a sticker sheet covers the target box `(targetX, targetY, targetW, targetH)`.
 */
export function computeSvgCropPlacement(
  url: string,
  targetX: number,
  targetY: number,
  targetW: number,
  targetH: number
): {
  href: string;
  x: number;
  y: number;
  width: number;
  height: number;
  preserveAspectRatio: string;
} {
  const { baseUrl, crop } = parseCropUrl(url);
  if (!crop) {
    return {
      href: baseUrl,
      x: targetX,
      y: targetY,
      width: targetW,
      height: targetH,
      preserveAspectRatio: 'xMidYMid slice',
    };
  }

  const scale = Math.max(targetW / crop.w, targetH / crop.h);
  const cx = crop.x + crop.w / 2;
  const cy = crop.y + crop.h / 2;
  const tx = targetX + targetW / 2;
  const ty = targetY + targetH / 2;

  return {
    href: baseUrl,
    x: Number((tx - cx * scale).toFixed(2)),
    y: Number((ty - cy * scale).toFixed(2)),
    width: Number((crop.sw * scale).toFixed(2)),
    height: Number((crop.sh * scale).toFixed(2)),
    preserveAspectRatio: 'none',
  };
}

/**
 * Returns `src` and optional CSS `objectViewBox` style for standard HTML `<img>` thumbnails
 * so cropped sticker-sheet reactions display their exact solo sub-region without extra DOM wrappers.
 */
export function getCropImgProps(url: string | null | undefined): {
  src: string;
  style?: { objectViewBox?: string };
} {
  const { baseUrl, crop } = parseCropUrl(url);
  if (!crop) {
    return { src: baseUrl };
  }
  const topPct = ((crop.y / crop.sh) * 100).toFixed(2);
  const rightPct = (((crop.sw - crop.x - crop.w) / crop.sw) * 100).toFixed(2);
  const bottomPct = (((crop.sh - crop.y - crop.h) / crop.sh) * 100).toFixed(2);
  const leftPct = ((crop.x / crop.sw) * 100).toFixed(2);
  return {
    src: baseUrl,
    style: {
      objectViewBox: `inset(${topPct}% ${rightPct}% ${bottomPct}% ${leftPct}%)`,
    },
  };
}

const dataUrlCache = new Map<string, string>();

/**
 * Converts a local image URL into a base64 data URL (cached) so serialized SVG blobs can render
 * `<image>` elements onto `<canvas>` during PNG & Sprite Sheet export.
 */
export async function toBase64DataUrl(srcUrl: string): Promise<string> {
  if (!srcUrl || srcUrl.startsWith('data:')) return srcUrl;
  const { baseUrl } = parseCropUrl(srcUrl);
  const cached = dataUrlCache.get(baseUrl);
  if (cached) return cached;

  return new Promise<string>((resolve) => {
    const img = new Image();
    img.crossOrigin = 'anonymous';
    img.onload = () => {
      try {
        const canvas = document.createElement('canvas');
        canvas.width = img.naturalWidth || 512;
        canvas.height = img.naturalHeight || 512;
        const ctx = canvas.getContext('2d');
        if (ctx) {
          ctx.drawImage(img, 0, 0);
          const dataUrl = canvas.toDataURL('image/jpeg', 0.92);
          dataUrlCache.set(baseUrl, dataUrl);
          resolve(dataUrl);
          return;
        }
      } catch {
        // fallback to original URL
      }
      resolve(baseUrl);
    };
    img.onerror = () => resolve(baseUrl);
    img.src = baseUrl;
  });
}

/**
 * Clones an `<svg>` element and inlines all `<image>` hrefs as base64 data URLs so
 * `XMLSerializer` + `Blob` -> `new Image()` renders embedded photos reliably.
 */
export async function serializeSvgWithInlinedImages(svgEl: SVGSVGElement): Promise<string> {
  const clone = svgEl.cloneNode(true) as SVGSVGElement;
  const images = Array.from(clone.querySelectorAll('image'));
  for (const imgNode of images) {
    const rawHref =
      imgNode.getAttribute('href') || imgNode.getAttribute('xlink:href') || '';
    if (rawHref && !rawHref.startsWith('data:')) {
      const dataUrl = await toBase64DataUrl(rawHref);
      imgNode.setAttribute('href', dataUrl);
    }
  }
  const serializer = new XMLSerializer();
  return serializer.serializeToString(clone);
}

